// Generate the Android drawable and animator resources.
//
// An AnimatedVectorDrawable only runs on RenderThread with animators inflated
// from resources, and there is no public API to change their duration after
// inflation. So there is one animator per supported duration (300 to 5000 ms in
// 100 ms steps) and one AVD per (pattern, duration). Run after changing the
// patterns or the range: node scripts/generate-android-res.mjs
import { mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const RES = 'android/src/main/res';
export const MIN_MS = 300;
export const MAX_MS = 5000;
export const STEP_MS = 100;
// Viewport: three periods of 100 units. Paths cover -100..400 so that a
// translateX of 0..100 always fills the viewport with the repeating pattern.
const PERIODS = [-1, 0, 1, 2, 3];

const patterns = {
  // A narrow band: transparent, opaque at the centre of each period, transparent.
  shimmer: [
    [0, '#00FFFFFF'],
    [0.36, '#00FFFFFF'],
    [0.5, '#FFFFFFFF'],
    [0.64, '#00FFFFFF'],
    [1, '#00FFFFFF'],
  ],
  // A triangle wave over the whole period. Drawn with a period many times wider
  // than the view, so the view sees one uniform alpha that rises and falls.
  pulse: [
    [0, '#00FFFFFF'],
    [0.5, '#FFFFFFFF'],
    [1, '#00FFFFFF'],
  ],
};

function vector(stops) {
  const paths = PERIODS.map((k) => {
    const x = k * 100;
    const items = stops.map(([o, c]) => `<item android:offset="${o}" android:color="${c}"/>`).join('');
    return `    <path android:pathData="M${x},0 h100 v10 h-100 z">
      <aapt:attr name="android:fillColor"><gradient android:type="linear" android:startX="${x}" android:startY="0" android:endX="${x + 100}" android:endY="0" android:tileMode="clamp">${items}</gradient></aapt:attr>
    </path>`;
  });
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/generate-android-res.mjs. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android" xmlns:aapt="http://schemas.android.com/aapt"
  android:width="300dp" android:height="10dp" android:viewportWidth="300" android:viewportHeight="10">
  <group android:name="band">
${paths.join('\n')}
  </group>
</vector>
`;
}

function animator(ms) {
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/generate-android-res.mjs. -->
<objectAnimator xmlns:android="http://schemas.android.com/apk/res/android"
  android:propertyName="translateX" android:valueFrom="0" android:valueTo="100" android:valueType="floatType"
  android:duration="${ms}" android:repeatCount="infinite" android:repeatMode="restart"
  android:interpolator="@android:anim/linear_interpolator"/>
`;
}

function avd(pattern, ms) {
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/generate-android-res.mjs. -->
<animated-vector xmlns:android="http://schemas.android.com/apk/res/android" android:drawable="@drawable/skeleton_native_${pattern}">
  <target android:name="band" android:animation="@animator/skeleton_native_slide_${ms}"/>
</animated-vector>
`;
}

function clean(dir) {
  mkdirSync(dir, { recursive: true });
  for (const f of readdirSync(dir)) if (f.startsWith('skeleton_native_')) rmSync(join(dir, f));
}

clean(join(RES, 'drawable'));
clean(join(RES, 'animator'));
for (const [name, stops] of Object.entries(patterns)) {
  writeFileSync(join(RES, 'drawable', `skeleton_native_${name}.xml`), vector(stops));
}
let count = 0;
for (let ms = MIN_MS; ms <= MAX_MS; ms += STEP_MS) {
  writeFileSync(join(RES, 'animator', `skeleton_native_slide_${ms}.xml`), animator(ms));
  for (const name of Object.keys(patterns)) {
    writeFileSync(join(RES, 'drawable', `skeleton_native_${name}_${ms}.xml`), avd(name, ms));
  }
  count++;
}
console.log(`generated ${count} durations x ${Object.keys(patterns).length} patterns`);

// Static references keep the resources through resource shrinking and avoid
// Resources.getIdentifier lookups at runtime.
const shimmerIds = [];
const pulseIds = [];
for (let ms = MIN_MS; ms <= MAX_MS; ms += STEP_MS) {
  shimmerIds.push(`R.drawable.skeleton_native_shimmer_${ms}`);
  pulseIds.push(`R.drawable.skeleton_native_pulse_${ms}`);
}
const wrap = (ids) => ids.map((id) => `    ${id},`).join('\n');
writeFileSync(
  'android/src/main/java/com/skeletonnative/SkeletonResources.java',
  `// Generated by scripts/generate-android-res.mjs. Do not edit.
package com.skeletonnative;

final class SkeletonResources {
  static final int MIN_MS = ${MIN_MS};
  static final int MAX_MS = ${MAX_MS};
  static final int STEP_MS = ${STEP_MS};

  static final int[] SHIMMER = {
${wrap(shimmerIds)}
  };

  static final int[] PULSE = {
${wrap(pulseIds)}
  };

  private SkeletonResources() {}

  /** The supported duration closest to {@code ms}. */
  static int quantize(int ms) {
    int clamped = Math.max(MIN_MS, Math.min(MAX_MS, ms));
    return MIN_MS + Math.round((clamped - MIN_MS) / (float) STEP_MS) * STEP_MS;
  }

  static int drawable(boolean pulse, int ms) {
    int index = (quantize(ms) - MIN_MS) / STEP_MS;
    return pulse ? PULSE[index] : SHIMMER[index];
  }
}
`,
);
